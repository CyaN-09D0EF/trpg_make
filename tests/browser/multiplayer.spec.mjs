import { test, expect } from '@playwright/test';

test('three independent browsers play one persistent campaign with private visions', async ({ browser, page: gm },testInfo) => {
  const errors=[];
  gm.on('pageerror',e=>errors.push(e.message));
  await gm.goto('/');
  await expect(gm.getByRole('heading',{name:/당신의 한 수가/})).toBeVisible();
  await gm.screenshot({path:testInfo.outputPath('landing.png'),fullPage:true});
  await gm.getByRole('button',{name:/새로운 세계 만들기/}).click();
  await gm.locator('.generation-rules summary').click();
  await expect(gm.locator('.generation-rules li')).toHaveCount(17);
  await expect(gm.locator('.generation-rules')).toContainText('깊은뿌리 부족');
  await gm.locator('.generation-rules summary').click();
  await gm.getByLabel('세계의 이름').fill('별을 품은 여명');
  await gm.getByLabel('GM 이름').fill('이야기꾼');
  await gm.getByRole('button',{name:/세계의 첫 장 열기/}).click();
  await expect(gm.getByRole('heading',{name:'미지의 땅, 우리의 세계'})).toBeVisible();
  await expect(gm.locator('#world-map [data-tile]')).toHaveCount(2280);
  await expect(gm.locator('.map-meta')).toContainText('2,280');
  await gm.getByRole('button',{name:'지도 확대',exact:true}).click();
  const map = gm.locator('#world-map');
  const viewBefore = await map.getAttribute('viewBox');
  const mapBounds = await map.boundingBox();
  await gm.mouse.move(mapBounds.x+mapBounds.width/2,mapBounds.y+mapBounds.height/2);
  await gm.mouse.down();
  await gm.mouse.move(mapBounds.x+mapBounds.width/2-90,mapBounds.y+mapBounds.height/2-40,{steps:8});
  await gm.mouse.up();
  await expect(map).not.toHaveAttribute('viewBox',viewBefore);
  await gm.getByRole('button',{name:'지도 초기화',exact:true}).click();

  await gm.getByRole('button',{name:'플레이어 초대'}).click();
  const godLink=await gm.getByLabel('신 초대 링크',{exact:true}).inputValue();
  const priestLink=await gm.getByLabel('신관 초대 링크',{exact:true}).inputValue();
  await gm.getByRole('button',{name:'닫기',exact:true}).click();
  const godContext=await browser.newContext(),priestContext=await browser.newContext();
  const god=await godContext.newPage(),priest=await priestContext.newPage();
  for(const p of [god,priest])p.on('pageerror',e=>errors.push(e.message));
  await god.goto(godLink);await god.getByLabel('플레이어 이름').fill('네뷸라 플레이어');await god.getByRole('button',{name:'이야기에 합류하기'}).click();
  await priest.goto(priestLink);await priest.getByLabel('플레이어 이름').fill('하루 플레이어');await priest.getByRole('button',{name:'이야기에 합류하기'}).click();
  await expect(gm.locator('.section-tiny').filter({hasText:'원탁의 동료들'})).toContainText('3/3');
  await god.getByRole('button',{name:'신 생성',exact:true}).click();
  await god.getByLabel('신의 이름').fill('네뷸라');await god.getByLabel('초기 소영역 하나').fill('곤충');
  await god.getByRole('button',{name:'신화의 첫 이름 새기기'}).click();
  await god.getByRole('button',{name:'시작 부족 선택'}).click();
  await god.getByRole('button',{name:'이 부족과 함께하기'}).click();
  await priest.getByRole('button',{name:'신관 생성',exact:true}).click();
  await priest.getByLabel('신관의 이름').fill('하루');await priest.getByRole('button',{name:'대지 위에 첫걸음 내딛기'}).click();
  await expect(gm.locator('.chapter-line')).toBeVisible();
  await priest.locator('#chat-message').fill('첫 번째 공동의 이야기');await priest.getByRole('button',{name:'메시지 보내기'}).click();
  await expect(god.locator('.log-list')).toContainText('첫 번째 공동의 이야기');
  await gm.locator('#chat-audience').selectOption('god');await gm.locator('#chat-message').fill('곤충만이 아는 비밀');await gm.getByRole('button',{name:'메시지 보내기'}).click();
  await expect(god.locator('.log-list')).toContainText('곤충만이 아는 비밀');
  await expect(priest.locator('.log-list')).not.toContainText('곤충만이 아는 비밀');
  await god.getByRole('button',{name:/신의 권능/}).click();await god.getByLabel('어떤 변화를 일으키나요?').fill('곤충이 풀을 먹게 하여 사슴의 이동을 유도한다.');await god.getByRole('button',{name:'GM에게 행동 제안하기'}).click();
  await gm.getByRole('button',{name:/행동 판정/}).click();await gm.getByRole('button',{name:'판정하기 →'}).click();await gm.getByLabel('신앙 비용').fill('2');await gm.getByLabel('결과와 변화').fill('작은 기적이 시작되었다. 동물의 이동은 GM이 관찰한다.');await gm.getByRole('button',{name:'판정 확정'}).click();
  await expect(god.locator('.stat').filter({hasText:'신앙'}).locator('.stat-value')).toContainText('8');
  await priest.getByRole('button',{name:/노동력 배치/}).click();await priest.getByLabel('농경',{exact:true}).fill('20');await priest.getByRole('button',{name:'노동 배치 저장'}).click();
  await gm.getByRole('button',{name:/시간 진행/}).click();await gm.getByRole('button',{name:'시간 진행 확정'}).click();
  await expect(priest.locator('.date-badge')).toContainText('2개월 차');
  await expect(gm.locator('.log-list')).toContainText('월말 정산');
  await gm.getByRole('button',{name:'타일 환경 편집 ↗'}).click();
  await gm.getByLabel('식물 자원량').fill('15');await gm.getByLabel('변경 사유').fill('기적에 의한 풀의 감소');
  await gm.getByRole('button',{name:'세계의 변화 적용'}).click();
  await expect(gm.locator('.tile-detail').filter({hasText:'식물 자원량'})).toContainText('15');
  await gm.screenshot({path:testInfo.outputPath('gm-world.png'),fullPage:true});
  await priest.screenshot({path:testInfo.outputPath('priest-world.png'),fullPage:true});
  await priest.reload();await expect(priest.locator('.date-badge')).toContainText('2개월 차');
  await priest.getByRole('button',{name:/문명 관리/}).click();await expect(priest.getByText('식량과 노동',{exact:false})).toBeVisible();
  await priest.setViewportSize({width:390,height:844});await priest.getByRole('button',{name:/세계 지도/}).click();
  await expect(priest.getByRole('heading',{name:'미지의 땅, 우리의 세계'})).toBeVisible();
  expect(await priest.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await priest.screenshot({path:testInfo.outputPath('mobile-world.png'),fullPage:true});
  await gm.setViewportSize({width:390,height:844});
  await gm.getByRole('button',{name:'플레이어 초대',exact:true}).click();
  await expect(gm.getByLabel('신 초대 링크',{exact:true})).toBeVisible();
  await gm.getByRole('button',{name:'닫기',exact:true}).click();
  // The catalog is visible to the GM; only discoveries reach either player.
  await gm.setViewportSize({width:1440,height:1100});
  await gm.getByRole('button',{name:/문명 관리/}).click();
  const tree = gm.locator('.tech-tree-board');
  await expect(tree.locator('.tech-node')).toHaveCount(67);
  // Exact data-name avoids selecting later technologies containing the same word.
  const sailingNode = tree.locator('[data-name="항해"]');
  await sailingNode.hover();
  await expect(sailingNode.locator('..').getByRole('tooltip')).toContainText('호수와 연안');
  await sailingNode.click();
  await gm.getByLabel('발전 단계').selectOption('1');
  await gm.getByRole('button',{name:'부족의 지식 기록'}).click();
  for (const player of [god,priest]) {
    await player.getByRole('button',{name:/문명 관리/}).click();
    await expect(player.locator('.tech-node')).toHaveCount(1);
    await expect(player.locator('.tech-node')).toContainText('항해');
    await expect(player.locator('.tech-node')).not.toContainText('조선');
    await expect(player.getByRole('button',{name:'기술 기록 +'})).toHaveCount(0);
  }
  await tree.locator('[data-name="조선"]').click();
  await expect(gm.getByLabel('기술 이름')).toHaveValue('조선');
  await gm.getByLabel('발전 단계').selectOption('2');
  await gm.getByRole('button',{name:'부족의 지식 기록'}).click();
  for (const player of [god,priest]) {
    await expect(player.locator('.tech-node')).toHaveCount(2);
    await expect(player.locator('.tech-connections path')).toHaveCount(1);
  }
  await priest.locator('[data-name="조선"]').click();
  await expect(priest.locator('[data-name="조선"]').locator('..').getByRole('tooltip')).toContainText('선박');
  expect(await priest.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const tip = await priest.locator('[data-name="조선"]').locator('..').getByRole('tooltip').boundingBox();
  expect(tip.x + tip.width).toBeLessThanOrEqual(390);
  await gm.screenshot({path:testInfo.outputPath('technology-tree-gm.png'),fullPage:true});
  await priest.screenshot({path:testInfo.outputPath('technology-tree-player-mobile.png'),fullPage:true});
  expect(errors).toEqual([]);
  await godContext.close();await priestContext.close();
});
