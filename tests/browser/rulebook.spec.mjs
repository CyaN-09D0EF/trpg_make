import {test,expect} from '@playwright/test';

test('rulebook matches the landing page, renders all chapters and supports search, anchors and raw download',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('/');
  const popupPromise=page.waitForEvent('popup');
  await page.getByRole('link',{name:'룰북 열기'}).click();
  const book=await popupPromise;
  book.on('pageerror',e=>errors.push(e.message));
  book.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await expect(book.getByRole('heading',{level:1})).toContainText('통합 룰북');
  expect(new URL(book.url()).pathname).toBe('/rulebook.md');
  await expect(book.locator('.rulebook-chapter')).toHaveCount(14);
  await expect(book.locator('.rulebook-toc a')).toHaveCount(14);
  await expect(book.locator('.rulebook-formula .katex')).toHaveCount(3);
  await expect(book.locator('.rulebook-formula math')).toHaveCount(3);
  await expect(book.locator('.rulebook-table').first().locator('th')).toContainText(['구분','신 플레이어','신관 플레이어']);
  await book.screenshot({path:testInfo.outputPath('rulebook-desktop.png'),fullPage:false});
  await book.getByRole('navigation',{name:'룰북 목차'}).getByRole('link',{name:'09 정착지와 인구'}).click();
  await expect(book).toHaveURL(/#chapter-9$/);
  await expect(book.locator('#chapter-9-title')).toBeInViewport();
  await expect(book.getByRole('navigation',{name:'룰북 목차'}).getByRole('link',{name:'09 정착지와 인구'})).toHaveAttribute('aria-current','location');
  await book.getByRole('searchbox',{name:'룰북 검색'}).fill('제단');
  await expect(book.locator('#rulebook-results')).toContainText('검색 결과 1개 장');
  await expect(book.locator('.rulebook-chapter:visible')).toHaveCount(1);
  await expect(book.locator('#chapter-2')).toBeVisible();
  await book.getByRole('searchbox',{name:'룰북 검색'}).fill('없는규칙abcdef');
  await expect(book.getByRole('heading',{name:'찾는 규칙이 없습니다'})).toBeVisible();
  await book.getByRole('button',{name:'전체 룰북 보기'}).click();
  await expect(book.locator('.rulebook-chapter:visible')).toHaveCount(14);
  const download=book.waitForEvent('download');
  await book.getByRole('link',{name:'원문 내려받기'}).click();
  expect((await download).suggestedFilename()).toBe('rulebook.md');
  await book.setViewportSize({width:390,height:844});
  await book.goto('/rulebook.md');
  await expect(book.locator('.rulebook-toc')).toBeVisible();
  expect(await book.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await book.screenshot({path:testInfo.outputPath('rulebook-mobile.png'),fullPage:false});
  await book.getByRole('navigation',{name:'룰북 목차'}).getByRole('link',{name:'07 식량 생산과 소비'}).click();
  await expect(book.locator('#chapter-7-title')).toBeInViewport();
  expect(await book.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await book.screenshot({path:testInfo.outputPath('rulebook-mobile-tables.png'),fullPage:false});
  await book.getByRole('link',{name:'목차 ↑',exact:true}).click();
  await expect(book.getByRole('searchbox',{name:'룰북 검색'})).toBeInViewport();
  await book.getByRole('link',{name:/시작 화면으로/}).click();
  await expect(book.getByRole('heading',{name:/당신의 한 수가/})).toBeVisible();
  expect(errors).toEqual([]);
});
