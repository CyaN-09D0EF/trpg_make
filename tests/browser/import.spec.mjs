import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('GM can download a campaign and restore it through the file picker into a separate persistent room', async ({ page }, testInfo) => {
  await page.goto('/');
  await page.getByRole('button',{name:/새로운 세계 만들기/}).click();
  await page.getByLabel('세계의 이름').fill('잃지 않을 세계');
  await page.getByLabel('GM 이름').fill('기록지기');
  await page.getByRole('button',{name:/세계의 첫 장 열기/}).click();
  await expect(page.getByRole('heading',{name:'미지의 땅, 우리의 세계'})).toBeVisible();
  const originalUrl=page.url();
  await page.getByRole('button',{name:'연대기',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'기록 JSON 내보내기'}).click();
  const download=await downloadPromise;
  const filePath=testInfo.outputPath(download.suggestedFilename());
  await download.saveAs(filePath);
  const exported=JSON.parse(await readFile(filePath,'utf8'));
  expect(exported.world.tiles).toHaveLength(2280);
  expect(exported.invite).toBeUndefined();
  expect(exported.players.gm.tokenHash).toBeUndefined();
  await page.getByRole('button',{name:'시작 화면으로'}).click();
  await page.getByRole('button',{name:'기록 불러오기',exact:true}).click();
  await page.getByLabel('GM 이름').fill('돌아온 GM');
  await page.getByLabel('기록 JSON 파일').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{broken')});
  await page.getByRole('button',{name:'세계 복원하기'}).click();
  await expect(page.locator('#toasts')).toContainText('JSON 파일을 읽을 수 없습니다');
  await expect(page.getByRole('button',{name:'세계 복원하기'})).toBeEnabled();
  await page.getByLabel('기록 JSON 파일').setInputFiles(filePath);
  await page.getByRole('button',{name:'세계 복원하기'}).click();
  await expect(page.getByRole('heading',{name:'미지의 땅, 우리의 세계'})).toBeVisible();
  expect(page.url()).not.toBe(originalUrl);
  await expect(page.locator('.room-label')).toContainText('잃지 않을 세계');
  await expect(page.locator('#world-map [data-tile]')).toHaveCount(2280);
  await page.reload();
  await expect(page.getByRole('heading',{name:'미지의 땅, 우리의 세계'})).toBeVisible();
  await page.getByRole('button',{name:'시작 화면으로'}).click();
  await expect(page.locator('.recent-card')).toHaveCount(2);
  await page.locator('.recent-card').nth(1).click();
  await expect(page).toHaveURL(originalUrl);
});
