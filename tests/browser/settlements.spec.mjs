import { test, expect } from '@playwright/test';
import { createGame, applyAction } from '../../lib/game.mjs';
import { generateWorld } from '../../lib/world.mjs';

test('GM manages mixed population, settlement density, adjacent expansion, city regions and major NPCs', async ({ page, browser, request }, testInfo) => {
  const campaign=createGame({id:'OLD123',name:'정착지의 시대',seed:'settlement-ui',gmName:'GM',gmHash:'old',invite:'old'});
  campaign.world=generateWorld(campaign.seed,{width:22,height:14});campaign.knowledge={god:{},priest:{}};
  applyAction(campaign,'god',{type:'create-god',name:'신',realm:'숲'});
  applyAction(campaign,'god',{type:'select-tribe',tribeId:'dawn'});
  applyAction(campaign,'priest',{type:'create-priest',name:'신관',strength:30,intelligence:40,social:30});
  const restored=await (await request.post('/api/rooms/import',{data:{campaign,playerName:'GM'}})).json();
  const {id,token,state}=restored;
  await page.goto('/');
  await page.evaluate(s=>localStorage.setItem('civilization.sessions',JSON.stringify([{id:s.id,token:s.token,role:'gm',name:s.state.name}])),restored);
  await page.goto(`/r/${id}`);
  await page.getByRole('button',{name:'문명 관리',exact:true}).click();
  await expect(page.locator('.settlement-item')).toHaveCount(1);
  await expect(page.locator('.settlement-item')).toContainText('촌락');
  await page.getByRole('button',{name:'종족별 인구 관리'}).click();
  await page.locator('.population-row').first().getByLabel('인구',{exact:true}).fill('40');
  await page.getByRole('button',{name:'종족 추가'}).click();
  const row=page.locator('.population-row').nth(1);
  await row.getByLabel('종족',{exact:true}).fill('엔트');
  await row.getByLabel('인구',{exact:true}).fill('16');
  await expect(row.getByLabel('1인 월간 소비')).toHaveValue('0');
  await page.getByLabel('인구 변경 사유').fill('숲의 주민 합류');
  await page.getByRole('button',{name:'인구 구성 저장'}).click();
  await expect(page.locator('.population-composition')).toContainText('엔트 16명');
  await expect(page.locator('.stats-strip')).toContainText('월간 소비 1,200');
  await page.getByRole('button',{name:'인접 정착지 확장'}).click();
  await page.getByLabel('정착지 이름').fill('강나루');
  await page.getByLabel('이주 인구').fill('10');
  await page.getByLabel('주거·시설의 타일 점유율').fill('50');
  await page.getByLabel('정착지 변경 사유').fill('새 주거지로 열 명 이주');
  await page.getByRole('button',{name:'새 정착지 건설'}).click();
  await expect(page.locator('.settlement-item')).toHaveCount(2);
  await expect(page.locator('.settlement-item').first()).toContainText('46명');
  await expect(page.locator('.settlement-item').nth(1)).toContainText('10명');
  await page.getByRole('button',{name:'종족별 인구 관리'}).click();
  const allocations=page.locator('#settlement-allocations fieldset');
  await allocations.nth(0).getByLabel('인간 배치 인구').fill('35');
  await page.getByLabel('인구 변경 사유').fill('정착지 사이 주민 재배치');
  await page.getByRole('button',{name:'인구 구성 저장'}).click();
  await expect(page.locator('#toasts')).toContainText('합계');
  await allocations.nth(0).getByLabel('엔트 배치 인구').fill('11');
  await allocations.nth(1).getByLabel('인간 배치 인구').fill('5');
  await allocations.nth(1).getByLabel('엔트 배치 인구').fill('5');
  await page.getByRole('button',{name:'인구 구성 저장'}).click();
  await expect(page.locator('.settlement-item').nth(1)).toContainText('엔트 5명');
  await page.locator('.settlement-item').nth(1).getByRole('button',{name:'단계·밀집도 관리'}).click();
  await page.getByLabel('정착지 단계').selectOption('1');
  await page.getByLabel('건물 밀집도').selectOption('3');
  await page.getByLabel('주거·시설의 타일 점유율').fill('75');
  await page.getByLabel('정착지 변경 사유').fill('주거 밀집과 시설 확대');
  await page.getByRole('button',{name:'정착지 변경 저장'}).click();
  await expect(page.locator('.settlement-item').nth(1)).toContainText('초고밀도');
  await page.getByRole('button',{name:'도시권 연결 관리'}).click();
  await page.getByLabel('도시권 변경 사유').fill('연결 도로와 공동 행정');
  await page.getByRole('button',{name:'도시권 변경 저장'}).click();
  await expect(page.locator('.urban-regions')).toContainText('여명 부족 ↔ 강나루');
  await page.getByRole('button',{name:'주요 NPC 기록 +'}).click();
  await page.getByLabel('NPC 이름').fill('나루지기');
  await page.getByLabel('NPC 역할').fill('장로');
  await page.getByLabel('소속 정착지').selectOption({label:'강나루'});
  await page.getByLabel('인물 설명').fill('강나루의 대표');
  await page.getByLabel('NPC 변경 사유').fill('대표 인물 지정');
  await page.getByRole('button',{name:'인물 기록 저장'}).click();
  await expect(page.locator('.notable-npcs')).toContainText('나루지기');
  const joined=await (await request.post(`/api/rooms/${id}/join`,{data:{role:'priest',name:'신관 플레이어',invite:state.invite}})).json();
  const ctx=await browser.newContext(),priest=await ctx.newPage();
  await priest.goto('/');
  await priest.evaluate(s=>localStorage.setItem('civilization.sessions',JSON.stringify([{id:s.id,role:s.role,token:s.token}])),joined);
  await priest.goto(`/r/${id}`);
  await priest.getByRole('button',{name:'문명 관리',exact:true}).click();
  await expect(priest.locator('.settlement-item')).toHaveCount(2);
  await expect(priest.locator('.notable-npcs')).toContainText('나루지기');
  await expect(priest.getByRole('button',{name:'종족별 인구 관리'})).toHaveCount(0);
  await expect(priest.getByRole('button',{name:'인접 정착지 확장'})).toHaveCount(0);
  await ctx.close();
  await page.reload();await page.getByRole('button',{name:'문명 관리',exact:true}).click();
  await expect(page.locator('.urban-regions')).toContainText('총 56명');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.settlement-panel').screenshot({path:testInfo.outputPath('settlements-mobile.png')});
  const exported=await (await request.get(`/api/rooms/${id}/export`,{headers:{Authorization:`Bearer ${token}`}})).json();
  const reimport=await request.post('/api/rooms/import',{data:{campaign:exported,playerName:'복원 GM'}});
  expect(reimport.status()).toBe(201);
  const reimported=(await reimport.json()).state.tribes[0];
  expect(reimported.settlements).toHaveLength(2);expect(reimported.population).toBe(56);
  expect(reimported.populationGroups[1].consumption).toBe(0);expect(reimported.urbanLinks).toHaveLength(1);
  expect(reimported.notableNpcs[0].name).toBe('나루지기');
});
