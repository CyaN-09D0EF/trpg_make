export const TECHNOLOGIES = rows.map(([name, era, prerequisites, description], i) => ({ id: `tech-${i+1}`, name, era, prerequisites, description }));

export function technologyTree(records, gm) {
  const stages = new Map(records.map(t => [t.name, t.stage]));
  const catalog = [...TECHNOLOGIES, ...records.filter(t => !TECHNOLOGIES.some(c => c.name === t.name)).map(t => ({ id: `custom:${t.name}`, name: t.name, era: '자유 기술', prerequisites: [], description: 'GM이 기록한 독자 기술입니다. 구체적인 활용과 효과는 GM의 판정에 따릅니다.' }))];
  const visible = catalog.filter(t => gm || (stages.get(t.name) || 0) > 0);
  const names = new Set(visible.map(t => t.name));
  return visible.map(t => ({ ...t, prerequisites: t.prerequisites.filter(n => names.has(n)), stage: stages.get(t.name) || 0 }));
}
